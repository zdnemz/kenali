#![forbid(unsafe_code)]

//! Package task. Stages release binaries, their separate PDBs and the SBOM
//! under `target/package/`. Owner-run on Windows; performs local file copies
//! only — no install, registration, signing or network access.

use anyhow::{Context, bail};
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

/// The exact release binaries that must be staged, with their real extensions.
const BINARIES: [&str; 4] = [
    "kenali-svc.exe",
    "kenali-cp.dll",
    "kenali-ui.exe",
    "kenali.exe",
];

/// Build the ordered list of (file name, required) pairs for all pinned
/// binaries. Kept separate from staging so it is testable on any host.
fn staging_plan() -> Vec<(String, bool)> {
    let mut plan = Vec::with_capacity(BINARIES.len() * 2);
    for name in BINARIES {
        let stem = name
            .strip_suffix(".exe")
            .or_else(|| name.strip_suffix(".dll"))
            .unwrap_or(name);
        plan.push((name.to_owned(), true));
        plan.push((format!("{stem}.pdb"), false));
    }
    plan
}

/// The release directory produced by the MSVC target build.
fn release_dir() -> PathBuf {
    Path::new("target")
        .join("x86_64-pc-windows-msvc")
        .join("release")
}

/// Staging root for the deliverable package.
fn package_dir() -> PathBuf {
    Path::new("target").join("package")
}

/// Stage binaries, PDBs and SBOM into target/package/.
pub fn package() -> anyhow::Result<()> {
    let src = release_dir();
    let dst = package_dir();
    println!("xtask package — staging {} -> {}", src.display(), dst.display());

    fs::create_dir_all(&dst)
        .with_context(|| format!("creating {}", dst.display()))?;

    let mut staged = 0usize;
    let plan = staging_plan();
    for (file, required) in &plan {
        let from = src.join(file);
        if !from.is_file() {
            // The matching PDB is optional; a pinned binary is required.
            if !required {
                continue;
            }
            bail!("package: required binary missing: {}", from.display());
        }
        let to = dst.join(file);
        fs::copy(&from, &to)
            .with_context(|| format!("copying {} to {}", from.display(), to.display()))?;
        println!("  staged {file}");
        staged += 1;
    }

    // Copy the SBOM if it exists (generated by `xtask sbom`).
    let version = env!("CARGO_PKG_VERSION");
    let sbom = Path::new("target")
        .join("sbom")
        .join(format!("kenali-{version}.cdx.xml"));
    if sbom.is_file() {
        let to = dst.join(format!("kenali-{version}.cdx.xml"));
        fs::copy(&sbom, &to)
            .with_context(|| format!("copying SBOM {} to {}", sbom.display(), to.display()))?;
        println!("  staged {}", to.display());
        staged += 1;
    } else {
        println!("  SBOM not found at {} (run `cargo xtask sbom` first)", sbom.display());
    }

    if staged == 0 {
        bail!("package: no files staged; build release binaries first");
    }
    println!("xtask package: staged {staged} file(s) into {}", dst.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn staging_plan_has_exactly_the_four_pinned_binaries_and_their_pdbs() {
        let plan = staging_plan();
        let expected = [
            ("kenali-svc.exe", true),
            ("kenali-svc.pdb", false),
            ("kenali-cp.dll", true),
            ("kenali-cp.pdb", false),
            ("kenali-ui.exe", true),
            ("kenali-ui.pdb", false),
            ("kenali.exe", true),
            ("kenali.pdb", false),
        ];
        let actual: Vec<(&str, bool)> = plan
            .iter()
            .map(|(name, required)| (name.as_str(), *required))
            .collect();
        assert_eq!(actual, expected);

        // Exactly four files are required, one for each pinned binary.
        let required: Vec<&str> = plan
            .iter()
            .filter(|(_, required)| *required)
            .map(|(name, _)| name.as_str())
            .collect();
        assert_eq!(required, ["kenali-svc.exe", "kenali-cp.dll", "kenali-ui.exe", "kenali.exe"]);

        // Never invent a cross-extension required file (the CI failure mode).
        assert!(!plan.iter().any(|(name, _)| name == "kenali-svc.dll"));
    }

    #[test]
    fn package_dir_is_target_package() {
        let s = package_dir().to_string_lossy().replace('\\', "/");
        assert_eq!(s, "target/package");
    }
}
